#!/usr/bin/env python3
# usage: mknet.py in.net out.h  -> C array NET_DATA for -DEMBED_NET builds
import sys
b = open(sys.argv[1], 'rb').read()
with open(sys.argv[2], 'w') as f:
    f.write('// generated by dev/mknet.py: network weights (%d bytes)\n' % len(b))
    f.write('static const unsigned char NET_DATA[%d] = {\n' % len(b))
    for i in range(0, len(b), 32):
        f.write(','.join(str(x) for x in b[i:i+32]) + ',\n')
    f.write('};\n')
